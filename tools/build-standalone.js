#!/usr/bin/env node
/* Builds wisp-standalone.html: the whole site in one file, nothing to install.
   Starts from index.html and inlines everything it references:
     · assets/css/wisp.css              -> a <style> block
     · every <script src>               -> an inline <script>
     · the Google Fonts stylesheet      -> assets/fonts/embedded-fonts.css
                                           (Newsreader + Playfair Display as
                                           data URIs; other faces fall back)
     · assets/img/badges/*.png          -> window.WISP_BADGE_IMG data URIs
     · typo.js + the en_US dictionary   -> <script type="text/plain"> blocks,
                                           which the grammar checker reads when
                                           fetch() is unavailable (file://)
   Run after changing anything the standalone should carry:
     node tools/build-standalone.js
*/
"use strict";
const fs = require("fs");
const path = require("path");

const ROOT = path.join(__dirname, "..");
const read = (p) => fs.readFileSync(path.join(ROOT, p), "utf8");

// Inside a <script>, a literal "</script" would end the block early. In
// JavaScript source the sequence can only occur inside a string or comment,
// where "<\/script" means exactly the same thing, so this swap is safe.
function jsSafe(src) { return src.replace(/<\/(script)/gi, "<\\/$1"); }
// Plain-text blocks (the dictionary) get no such escape; refuse rather than
// silently corrupt if one ever contains the sequence.
function textSafe(src, name) {
  if (/<\/script/i.test(src)) throw new Error(name + " contains '</script'; cannot inline as text");
  return src;
}

let html = read("index.html");

// 1. Fonts: swap the Google Fonts tags for the embedded faces.
const fontsCss = read("assets/fonts/embedded-fonts.css");
html = html
  .replace(/[ \t]*<link rel="preconnect"[^>]*>\s*\n/g, "")
  .replace(/[ \t]*<link href="https:\/\/fonts\.googleapis\.com[^>]*>\s*\n/,
    "  <style>" + fontsCss + "</style>\n");

// 2. The stylesheet.
html = html.replace(/<link rel="stylesheet" href="assets\/css\/wisp\.css">/,
  () => "<style>\n" + read("assets/css/wisp.css") + "\n</style>");

// 3. The badge art, as data URIs, defined before badges.js reads it.
const badgeDir = path.join(ROOT, "assets/img/badges");
const badges = {};
fs.readdirSync(badgeDir).filter(f => f.endsWith(".png")).sort().forEach(f => {
  badges[f] = "data:image/png;base64," + fs.readFileSync(path.join(badgeDir, f)).toString("base64");
});
const badgeScript = "<script>\n/* Badge art, inlined so the one-file build needs no assets folder. */\n" +
  "window.WISP_BADGE_IMG = " + JSON.stringify(badges) + ";\n</script>\n";

// 4. The grammar checker's worker sources, as inert text blocks. gcText() in
//    wisp.js reads these by id before trying fetch(), so spellcheck works from
//    file:// where fetch is blocked.
const grammarBlocks =
  '<script type="text/plain" id="wisp-typo-src">' + textSafe(read("assets/js/typo.js"), "typo.js") + "</script>\n" +
  '<script type="text/plain" id="wisp-dict-aff">' + textSafe(read("assets/dict/en_US.aff"), "en_US.aff") + "</script>\n" +
  '<script type="text/plain" id="wisp-dict-dic">' + textSafe(read("assets/dict/en_US.dic"), "en_US.dic") + "</script>\n";

// 5. Every referenced script, inlined in order. The badge data URIs go in just
//    before badges.js.
html = html.replace(/<script src="([^"]+)"><\/script>/g, (m, src) => {
  const inline = "<script>\n" + jsSafe(read(src)) + "\n</script>";
  if (src.endsWith("badges.js")) return badgeScript + inline;
  return inline;
});

// 6. The grammar text blocks sit at the end of body, after all the scripts.
//    Splice at the LAST </body>: the inlined app code carries "</body>" inside
//    its EPUB-export template strings, so a first-match replace would bury
//    these blocks inside a JavaScript string.
const bodyEnd = html.lastIndexOf("</body>");
if (bodyEnd < 0) throw new Error("no </body> in index.html");
html = html.slice(0, bodyEnd) + grammarBlocks + html.slice(bodyEnd);

// 7. A build stamp so a stale copy is easy to spot.
html = html.replace(/<head>/, "<head>\n<!-- Generated by tools/build-standalone.js; edit assets/ and rebuild rather than editing this file. -->");

fs.writeFileSync(path.join(ROOT, "wisp-standalone.html"), html);
const mb = (fs.statSync(path.join(ROOT, "wisp-standalone.html")).size / 1024 / 1024).toFixed(2);
console.log("wisp-standalone.html rebuilt (" + mb + " MB)");
